// Remedy Match versus Biofield on the rendered portal (Glen, 2026-10-20, approved
// wording). The page body is built by tests/lib/portal-render-harness.js's slice of
// render(), with the real reportWords() helper in scope, so this asserts on what a
// client would see rather than on what the source says. A paid Biofield keeps every
// word it had; a missing kind reads as Biofield.
const assert = require('assert');
const harness = require('./lib/portal-render-harness.js');

const src = harness.read();

function fnSource(name) {
  const at = src.indexOf('\nfunction ' + name + '(');
  assert.ok(at !== -1, 'function ' + name + '() not found');
  const end = src.indexOf('\n}', at);
  return src.slice(at, end + 2);
}
// A multi-line top-level const, through its closing "};".
function constBlock(marker) {
  const i = src.indexOf(marker);
  assert.ok(i !== -1, 'source block not found: ' + marker);
  return src.slice(i, src.indexOf('\n};', i) + 3);
}
function line(marker) {
  const i = src.indexOf(marker);
  assert.ok(i !== -1, 'source line not found: ' + marker);
  return src.slice(i, src.indexOf('\n', i));
}

// Builders outside the slice that the report card calls. Each has its own test.
const STUBS = harness.STUBS.concat(['foldSlug', 'terrainBanner', 'scheduleHtml',
                                    'dietGuidanceHtml']);
const code = [
  line('const esc = '), line('const money = '), line('const ICON_LOCK = '),
  line('const ICON_INFO = '),
  constBlock('const fmtDate = '),
  fnSource('backToHub'), fnSource('backToHome'), fnSource('reportWords'),
  '(function(d, v, _hub, _shell, _doors, seg, token, onboardingMount, hubHtml, first, badges, recSections, _ppTimer, location, window){',
  STUBS.map(n => '  var ' + n + ' = function(){ return ""; };').join('\n'),
  // The pending card polls; the harness never runs a timer.
  '  var _ppPolls = 0, PP_MAX = 10, _ppPosted = true, pollPending = function(){};',
  '  var localStorage = {getItem: function(){ return "1"; }, setItem: function(){}};',
  '  var setInterval = function(){ return 1; }, clearInterval = function(){};',
  harness.slice(src),
  '  return html;',
  '})'
].join('\n');
const renderFn = (0, eval)(code); // eslint-disable-line no-eval

function render(d, v) {
  return renderFn(d, v || {}, false, false, false, 'SEG', 'TOK', null, '', 'Gita', [], [], null,
    { origin: 'https://example.test', href: 'https://example.test/portal/SEG', search: '' },
    { PortalConditions: require('../static/js/portal-conditions.js') });
}

const LAYERS = [{ n: 1, title: 'Liver', meaning: 'm' }];
function report(kind, status, extra) {
  return Object.assign({ name: 'Gita Wright', biofield_status: status, report_kind: kind,
                         layers: LAYERS, scan_date: '2026-10-14', greeting: 'Aloha Gita' },
                       extra || {});
}

const AI_NOTICE = 'Generated by Dr. Glen&#39;s knowledgebase.';
const OLD_NOTICE = "AI-generated, pending Dr. Glen";
const RM_LINE = 'See which remedies match to your scan. Your Remedy Match is <a href="#biofield-section" class="rm-here" onclick="return scrollToReportPart(\'biofield-section\')">here</a>.';

// The id "here" points at must be on an element that encloses the line itself: this
// report's own card, never another feature's card and never an id nothing renders.
function linkLandsInItsOwnCard(html) {
  const at = html.indexOf(RM_LINE);
  if (at === -1) return false;
  const open = html.lastIndexOf('id="biofield-section"', at);
  if (open === -1) return false;
  const cardStart = html.lastIndexOf('<div', open);
  // Nothing between the card's opening tag and the line may close that card.
  const between = html.slice(cardStart, at);
  const opens = (between.match(/<div\b/g) || []).length;
  const closes = (between.match(/<\/div>/g) || []).length;
  return opens > closes;
}
const BF_LINE = 'Your Biofield Analysis is ready: your healing path, mapped from the surface layer down to the deepest root.';

// esc() leaves an apostrophe alone, so accept either spelling of the notice.
function hasNotice(html) {
  return html.indexOf(AI_NOTICE) !== -1 || html.indexOf("Generated by Dr. Glen's knowledgebase.") !== -1;
}

// --- The ai_draft card ---
{
  const html = render(report('remedy_match', 'ai_draft'));
  assert.ok(html.indexOf(RM_LINE) !== -1, 'Remedy Match ready line missing');
  assert.ok(linkLandsInItsOwnCard(html), '"here" must point at its own report card');
  assert.strictEqual((html.match(/id="biofield-section"/g) || []).length, 1,
    'exactly one element carries the target id');
  assert.ok(html.indexOf(BF_LINE) === -1, 'a Remedy Match must not say Biofield Analysis');
  assert.ok(hasNotice(html), 'a Remedy Match draft shows the knowledgebase notice');
  assert.ok(html.indexOf(OLD_NOTICE) === -1, 'the old AI notice is gone');
}
{
  const html = render(report('biofield', 'ai_draft'));
  assert.ok(html.indexOf(BF_LINE) !== -1, 'a paid Biofield draft keeps its line');
  assert.ok(!hasNotice(html) && html.indexOf(OLD_NOTICE) === -1,
    'a paid Biofield draft is Glen\'s handwritten work and shows no AI notice');
  assert.ok(html.indexOf('class="disclose"') === -1, 'no empty notice paragraph either');
}
{
  // No kind at all: what the page said before report_kind existed, minus the AI notice.
  const html = render(report(undefined, 'ai_draft'));
  assert.ok(html.indexOf(BF_LINE) !== -1);
  assert.ok(!hasNotice(html));
}

// --- With no target, "here" is plain text, never a dead link ---
{
  // No page state renders the line without its card today, so this drives the
  // helper the card calls, with the target it would pass when neither exists.
  const words = (0, eval)([line('const esc = '), constBlock('const fmtDate = '), fnSource('reportWords'),
                               '(reportWords)'].join('\n'));
  const plain = words('remedy_match').readyHtml(null);
  assert.strictEqual(plain, 'See which remedies match to your scan. Your Remedy Match is here.');
  assert.ok(plain.indexOf('<a') === -1);
  assert.strictEqual(words('remedy_match').readyHtml(''), plain);
}

// --- The card follows the report it shows ---
{
  // Off a member tab the card renders the view block (v.biofield), which can be a
  // different report from the payload's. Its kind must win.
  const v = { biofield: { visible: true, status: 'ai_draft', report_kind: 'remedy_match',
                          layers: LAYERS, scan_date: '2026-10-14', scan_dates: ['2026-10-14'] } };
  const html = render(report('biofield', 'ai_draft'), v);
  assert.ok(html.indexOf(RM_LINE) !== -1, 'the view block\'s kind decides the words');
  const v2 = { biofield: Object.assign({}, v.biofield, { report_kind: 'biofield' }) };
  assert.ok(render(report('remedy_match', 'ai_draft'), v2).indexOf(BF_LINE) !== -1);
}

// --- The interested state carries the notice in the report body ---
{
  assert.ok(hasNotice(render(report('remedy_match', 'interested'))));
  assert.ok(!hasNotice(render(report('biofield', 'interested'))));
}

// --- The read-receipt header ---
{
  const rm = render(report('remedy_match', 'confirmed', { opens: {} }));
  assert.ok(rm.indexOf('<strong>Remedy Match, Oct 14, 2026</strong>') !== -1, 'Remedy Match header');
  assert.ok(rm.indexOf('Biofield report') === -1);
  assert.ok(!hasNotice(rm), 'a confirmed report keeps today\'s rule: no notice once confirmed');
  const bf = render(report('biofield', 'confirmed', { opens: {} }));
  assert.ok(bf.indexOf('<strong>Biofield report — 2026-10-14</strong>') !== -1, 'Biofield header unchanged');
}

// --- The pending card is only ever a Remedy Match ---
{
  const html = render({ name: 'Gita', biofield_status: 'pending', scan_date: '2026-10-14' });
  assert.ok(html.indexOf('<h2>Preparing your Remedy Match…</h2>') !== -1);
  assert.ok(html.indexOf('Biofield Analysis') === -1);
}

// --- The options card ---
{
  const html = render({ name: 'Gita', options: { analysis_cents: 30000, ff_from_cents: 3500 } });
  assert.ok(html.indexOf('<strong>Your Remedy Match</strong>: your Bioenergetic Wellness Scan reading and your personally matched remedies, right here in your private space.') !== -1,
    'options card line');
  assert.ok(html.indexOf('voice-scan reading') === -1);
  // The paid offer on the next line still names the Biofield.
  assert.ok(html.indexOf('Personal Causal Biofield Analysis with Dr. Glen') !== -1);
}

// --- The printed page and its PDF ---
{
  const at = src.indexOf('const PRINT_HEADER = ');
  const header = src.slice(at, src.indexOf('</div>`;', at) + 8);
  const build = (0, eval)([
    line('const esc = '), constBlock('const fmtDate = '),
    'var terrainBanner = function(){ return ""; }, dietGuidanceHtml = function(){ return ""; };',
    'var escGreeting = function(x){ return String(x); };',
    header, fnSource('reportWords'), fnSource('buildReportPrintHtml'),
    '(buildReportPrintHtml)'].join('\n'));
  const title = (d) => /<div class="pd-title">([^<]*)<\/div>/.exec(build(d))[1];
  assert.strictEqual(title({ report_kind: 'remedy_match' }), 'Remedy Match');
  assert.strictEqual(title({ report_kind: 'biofield' }), 'Biofield Analysis');
  assert.strictEqual(title({}), 'Biofield Analysis');
}

// --- "From the surface layer down to the deepest root" is Biofield wording only ---
// Glen, 2026-10-20: layers wording is reserved for the paid causal analysis.
{
  const SURFACE = 'From the surface layer down to the deepest root, we support them in order, and the whole chain unwinds.';
  for (const status of ['interested', 'confirmed']) {
    assert.ok(render(report('remedy_match', status)).indexOf(SURFACE) === -1,
      'no surface-layer line on a Remedy Match (' + status + ')');
    assert.ok(render(report('biofield', status)).indexOf(SURFACE) !== -1,
      'a Biofield keeps the surface-layer line (' + status + ')');
    // A report whose kind the page cannot tell keeps today's Biofield text.
    assert.ok(render(report(undefined, status)).indexOf(SURFACE) !== -1);
  }
  // The read-receipt variant renders the same body.
  assert.ok(render(report('remedy_match', 'confirmed', { opens: {} })).indexOf(SURFACE) === -1);
  assert.ok(render(report('biofield', 'confirmed', { opens: {} })).indexOf(SURFACE) !== -1);
}

// --- The printed page and its PDF: the same rule ---
{
  const PRINT_SURFACE = 'From the surface layer down to the deepest root, supported in order, so the whole chain unwinds.';
  const at = src.indexOf('const PRINT_HEADER = ');
  const header = src.slice(at, src.indexOf('</div>`;', at) + 8);
  const build = (0, eval)([
    line('const esc = '), constBlock('const fmtDate = '),
    'var terrainBanner = function(){ return ""; }, dietGuidanceHtml = function(){ return ""; };',
    'var escGreeting = function(x){ return String(x); };',
    header, fnSource('reportWords'), fnSource('buildReportPrintHtml'),
    '(buildReportPrintHtml)'].join('\n'));
  const page = (kind) => build({ report_kind: kind, layers: LAYERS });
  assert.ok(page('remedy_match').indexOf(PRINT_SURFACE) === -1, 'no surface-layer line in a Remedy Match PDF');
  assert.ok(page('remedy_match').indexOf('<h3>Your healing path</h3>') !== -1, 'the path itself still prints');
  assert.ok(page('biofield').indexOf(PRINT_SURFACE) !== -1, 'a Biofield PDF keeps it');
  assert.ok(page(undefined).indexOf(PRINT_SURFACE) !== -1, 'an unknown kind keeps it');
}

// --- The reveal page (always a Remedy Match): patterns, not layers ---
{
  const reveal = require('fs').readFileSync(
    require('path').join(__dirname, '..', 'static', 'begin-biofield.html'), 'utf8');
  const at = reveal.indexOf('function renderLayers(root, data) {');
  assert.ok(at !== -1, 'renderLayers not found');
  const fnText = reveal.slice(at, reveal.indexOf('\n      }\n', at) + 8);
  const el = (tag) => ({ tag, className: '', textContent: '', children: [],
                         appendChild(c) { this.children.push(c); } });
  const renderLayers = (0, eval)('(function(document, renderRemedyInto){ ' + fnText +
                                 '\n return renderLayers; })')({ createElement: el }, function(){});
  const root = el('div');
  renderLayers(root, { layers: [{ n: 2, remedy_blurred: true }, { title: 'Liver', n: 3 }] });
  const texts = root.children.map(sec => sec.children.map(c => c.textContent));
  assert.deepStrictEqual(texts[0], ['Pattern 2', 'Your Remedy Match for this pattern']);
  assert.deepStrictEqual(texts[1], ['Liver']);
}

